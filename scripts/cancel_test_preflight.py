"""Authenticated, read-only preflight for the supervised Phase 4A cancellation test.

The bearer token is read from BURP_MCP_TOKEN only when making MCP calls. It is
never printed, placed on a command line, or written to disk. The only HTTP
request made by this preflight is a direct loopback GET to the server's
non-logging health route; it never sends /test-cancel.
"""

import http.client
import itertools
import json
import os
import re
import socket
import sys
import time


MCP_HOST = "127.0.0.1"
MCP_PORT = 9876
MCP_PATH = "/mcp"
PROXY_HOST = "127.0.0.1"
PROXY_PORT = 8080
TARGET_URL = "http://127.0.0.1:8000/test-cancel"
LOCAL_TEST_PATHS = (
    "/test-html",
    "/test-post",
    "/test-form",
    "/test-upload",
    "/test-cancel",
    "/test-timeout",
    "/test-session-expiry",
    "/test-concurrent-a",
    "/test-concurrent-b",
)
LOCAL_TEST_URLS = tuple(f"http://127.0.0.1:8000{path}" for path in LOCAL_TEST_PATHS)
HEALTH_PATH = "/__phase4a-health"
HEALTH_BODY = b"MCP_LOCAL_TEST_SERVER_READY"
EXPECTED_BUILD_ID = "20261101.5-burp2024.1.1.1"
EXPECTED_BURP_VERSION_PREFIX = "Burp Suite Professional 2024.1.1.1"
# The queue drops held messages at 120s and the client observes cancellation up
# to 125s. Keep 25s beyond the client deadline for scheduling and cleanup.
INTERCEPTED_MESSAGE_TIMEOUT_MS = 120_000
CLIENT_OBSERVATION_DEADLINE_MS = 125_000
POST_REQUEST_SAFETY_MARGIN_MS = 25_000
MIN_REMAINING_MS = max(
    INTERCEPTED_MESSAGE_TIMEOUT_MS, CLIENT_OBSERVATION_DEADLINE_MS
) + POST_REQUEST_SAFETY_MARGIN_MS
# Setup runs before a human starts a fresh interception session. Keep 30s for
# that required Burp-local action in addition to the 150s test safety budget.
SESSION_ACTIVATION_MARGIN_MS = 30_000
MIN_SETUP_AUTHORIZATION_MS = MIN_REMAINING_MS + SESSION_ACTIVATION_MARGIN_MS
PROTOCOL_VERSION = "2025-03-26"
TOKEN_PATTERN = re.compile(r"^[A-Za-z0-9_-]{43}$")
MAX_MCP_RESPONSE_BYTES = 1_048_576


class PreflightError(RuntimeError):
    pass


def bearer_token_from_environment(environ=None):
    """Return only a bare token in the exact encoding generated by this extension."""
    env = os.environ if environ is None else environ
    token = env.get("BURP_MCP_TOKEN")
    if token is None:
        raise PreflightError("BURP_MCP_TOKEN is missing; authenticated MCP checks cannot run")
    if token == "":
        raise PreflightError("BURP_MCP_TOKEN is empty; authenticated MCP checks cannot run")
    if token != token.strip() or not TOKEN_PATTERN.fullmatch(token):
        raise PreflightError(
            "BURP_MCP_TOKEN must be the bare 43-character token from Burp (no Bearer prefix or whitespace)"
        )
    return token


def _validate_snapshot_basics(snapshot):
    """Check shared authenticated-server, target, and queue prerequisites."""
    failures = []
    connection = snapshot.get("connection")
    server = snapshot.get("server")
    scope = snapshot.get("scope")
    interception = snapshot.get("interception")
    requests = snapshot.get("requests")
    responses = snapshot.get("responses")

    if not isinstance(connection, dict):
        connection = {}
        failures.append("MCP connection status is missing")
    if connection.get("burpConnected") is not True:
        failures.append("Burp MCP connection is not healthy")
    if connection.get("serverState") != "running":
        failures.append("Burp MCP listener is not running")
    if not str(connection.get("burpVersion", "")).startswith(EXPECTED_BURP_VERSION_PREFIX):
        failures.append("Burp version does not match Professional 2024.1.1.1")

    if not isinstance(server, dict):
        server = {}
        failures.append("Burp MCP server status is missing")
    if server.get("serverState") != "running" or server.get("lastError") is not None:
        failures.append("Burp MCP server is not healthy")
    if server.get("buildId") != EXPECTED_BUILD_ID:
        failures.append(f"Loaded extension build does not match expected build {EXPECTED_BUILD_ID}")
    if server.get("bearerAuthenticationRequired") is not True:
        failures.append("MCP bearer authentication is not confirmed")
    if server.get("readOnlyMode") is not False:
        failures.append("Burp MCP read-only mode prevents the approved drop action")

    scope_checks = scope.get("checks", []) if isinstance(scope, dict) else []
    matching_scope = [
        check for check in scope_checks
        if isinstance(check, dict) and check.get("url") == TARGET_URL
    ]
    if len(matching_scope) != 1:
        failures.append("Exact /test-cancel scope result is missing or ambiguous")
    else:
        check = matching_scope[0]
        if check.get("inBurpScope") is not True:
            failures.append("/test-cancel is not in Burp Target scope")
        if check.get("hostAllowlisted") is not True:
            failures.append("/test-cancel host is not in the MCP allowlist")
        if check.get("eligible") is not True:
            failures.append("/test-cancel is not eligible")

    if not isinstance(interception, dict):
        interception = {}
        failures.append("Live interception status is missing")

    try:
        pending_requests = int(interception.get("pendingRequests", -1))
        pending_responses = int(interception.get("pendingResponses", -1))
    except (TypeError, ValueError):
        pending_requests = pending_responses = -1
    if pending_requests != 0:
        failures.append("Interception request queue is not empty")
    if pending_responses != 0:
        failures.append("Interception response queue is not empty")
    if not isinstance(requests, list) or requests:
        failures.append("Pending request listing is missing or non-empty")
    if not isinstance(responses, list) or responses:
        failures.append("Pending response listing is missing or non-empty")

    return failures, interception


def _validate_unattended_identity(interception, unattended_run_id, unattended_server_identity):
    failures = []
    mode = interception.get("unattendedMode")
    if not isinstance(mode, dict) or mode.get("active") is not True:
        failures.append("Unattended local test mode is not active")
        return failures
    active_run_id = mode.get("testRunId")
    active_server_identity = mode.get("serverIdentity")
    if not active_run_id or not active_server_identity:
        failures.append("Both active unattended test identities are required")
    if bool(unattended_run_id) != bool(unattended_server_identity):
        failures.append("Both supplied unattended test identities are required")
    elif unattended_run_id is not None and (
        active_run_id != unattended_run_id or active_server_identity != unattended_server_identity
    ):
        failures.append("Supplied test identity does not match the active Burp-local authorization")
    return failures


def validate_setup_snapshot(snapshot, unattended_run_id=None, unattended_server_identity=None):
    """Verify authentication and fixture prerequisites before starting interception."""
    failures, interception = _validate_snapshot_basics(snapshot)
    if interception.get("enabled") is not False:
        failures.append("Live interception must be inactive during setup preflight")
    failures.extend(_validate_unattended_identity(
        interception, unattended_run_id, unattended_server_identity
    ))
    mode = interception.get("unattendedMode")
    try:
        authorization_remaining_ms = int(mode.get("remainingMillis", 0)) if isinstance(mode, dict) else 0
    except (TypeError, ValueError):
        authorization_remaining_ms = 0
    if authorization_remaining_ms < MIN_SETUP_AUTHORIZATION_MS:
        failures.append(
            f"Unattended authorization has less than {MIN_SETUP_AUTHORIZATION_MS // 1000}s remaining "
            "to activate interception and complete the test safely"
        )
    return failures


def validate_mcp_snapshot(snapshot, minimum_remaining_ms=MIN_REMAINING_MS,
                          unattended_run_id=None, unattended_server_identity=None,
                          minimum_session_lifetime_seconds=300):
    """Return safe, user-readable failed checks for an active-session snapshot."""
    failures, interception = _validate_snapshot_basics(snapshot)
    if interception.get("enabled") is not True:
        failures.append("Live interception is not active")
    if interception.get("heartbeatHealth") != "HEALTHY":
        failures.append("Live interception heartbeat is not healthy")
    try:
        session_lifetime_seconds = int(interception.get("sessionLifetimeSeconds", 0))
    except (TypeError, ValueError):
        session_lifetime_seconds = 0
    if session_lifetime_seconds < minimum_session_lifetime_seconds:
        failures.append(
            f"Live interception lifetime is below the requested {minimum_session_lifetime_seconds}-second minimum"
        )
    if interception.get("sessionEndReason") != "NONE":
        failures.append("Live interception session has ended or is ending")
    if interception.get("timeoutSeconds") != INTERCEPTED_MESSAGE_TIMEOUT_MS // 1000:
        failures.append("Interception message timeout is not the validated 120-second limit")
    failures.extend(_validate_unattended_identity(
        interception, unattended_run_id, unattended_server_identity
    ))

    try:
        remaining_ms = int(interception.get("sessionRemainingMillis", 0))
    except (TypeError, ValueError):
        remaining_ms = 0
    if remaining_ms < minimum_remaining_ms:
        failures.append(
            f"Live interception has less than {minimum_remaining_ms // 1000}s remaining "
            "for the client deadline and safety margin"
        )
    mode = interception.get("unattendedMode")
    try:
        authorization_remaining_ms = int(mode.get("remainingMillis", 0)) if isinstance(mode, dict) else 0
    except (TypeError, ValueError):
        authorization_remaining_ms = 0
    if authorization_remaining_ms < minimum_remaining_ms:
        failures.append(
            f"Unattended authorization has less than {minimum_remaining_ms // 1000}s remaining "
            "for the client deadline and safety margin"
        )
    try:
        lease_remaining_ms = int(interception.get("leaseRemainingMillis", 0))
    except (TypeError, ValueError):
        lease_remaining_ms = 0
    if lease_remaining_ms <= 0:
        failures.append("Live interception heartbeat lease has expired")
    return failures


class McpClient:
    def __init__(self, connection_factory=http.client.HTTPConnection, host=MCP_HOST,
                 port=MCP_PORT, timeout=5):
        self._ids = itertools.count(1)
        self._session_id = None
        self._protocol_version = PROTOCOL_VERSION
        self._connection_factory = connection_factory
        self._host = host
        self._port = port
        self._timeout = timeout

    def rpc(self, method, params=None, notification=False):
        token = bearer_token_from_environment()

        message = {"jsonrpc": "2.0", "method": method}
        if params is not None:
            message["params"] = params
        if not notification:
            message["id"] = next(self._ids)

        headers = {
            "Authorization": "Bearer " + token,
            "Content-Type": "application/json",
            "Accept": "application/json, text/event-stream",
            "MCP-Protocol-Version": self._protocol_version,
        }
        if self._session_id:
            headers["Mcp-Session-Id"] = self._session_id

        connection = None
        try:
            connection = self._connection_factory(self._host, self._port, timeout=self._timeout)
            connection.request("POST", MCP_PATH, json.dumps(message), headers)
            response = connection.getresponse()
            self._session_id = response.getheader("Mcp-Session-Id") or self._session_id
            content_type = response.getheader("Content-Type", "").split(";", 1)[0].strip().lower()
            if response.status == 401:
                raise PreflightError(
                    "MCP authentication rejected BURP_MCP_TOKEN (HTTP 401); refresh it from Burp's Security tab"
                )
            if response.status == 403:
                raise PreflightError("MCP rejected the request (HTTP 403); check local MCP request policy")
            if response.status >= 400:
                raise PreflightError(f"Authenticated MCP request failed with HTTP {response.status}")
            if notification:
                return None

            if content_type == "text/event-stream":
                payload = self._read_sse_result(response, message.get("id"), method)
            else:
                if content_type != "application/json":
                    raise PreflightError(f"MCP {method} returned an unexpected content type")
                body = response.read(MAX_MCP_RESPONSE_BYTES + 1)
                if len(body) > MAX_MCP_RESPONSE_BYTES:
                    raise PreflightError(f"MCP {method} response exceeded the bounded size limit")
                try:
                    payload = json.loads(body.decode("utf-8", errors="strict"))
                except json.JSONDecodeError as error:
                    raise PreflightError(f"MCP {method} returned an unreadable response") from error
                except UnicodeDecodeError as error:
                    raise PreflightError(f"MCP {method} returned a non-UTF-8 response") from error

            if not isinstance(payload, dict) or payload.get("jsonrpc") != "2.0":
                raise PreflightError(f"MCP {method} returned a malformed JSON-RPC response")
            if type(payload.get("id")) is not type(message.get("id")) or payload.get("id") != message.get("id"):
                raise PreflightError(f"MCP {method} returned a mismatched response ID")
            if "error" in payload:
                error = payload.get("error")
                if not isinstance(error, dict) or not isinstance(error.get("code"), int):
                    raise PreflightError(f"MCP {method} returned a malformed JSON-RPC error")
                raise PreflightError(f"MCP {method} returned a JSON-RPC error (code {error['code']})")
            return payload.get("result")
        except PreflightError:
            raise
        except TimeoutError as error:
            raise PreflightError(f"MCP {method} timed out; the cancellation test request was not sent") from error
        except ConnectionRefusedError as error:
            raise PreflightError(f"MCP {method} connection was refused; the cancellation test request was not sent") from error
        except OSError as error:
            raise PreflightError(f"MCP {method} network failure ({type(error).__name__}); the cancellation test request was not sent") from error
        except Exception as error:
            raise PreflightError(f"MCP {method} failed ({type(error).__name__})") from error
        finally:
            if connection is not None:
                connection.close()

    @staticmethod
    def _read_sse_result(response, expected_id, method):
        """Read only until the matching SSE result, without waiting for stream EOF."""
        total = 0
        data_lines = []
        while total <= MAX_MCP_RESPONSE_BYTES:
            line = response.readline(MAX_MCP_RESPONSE_BYTES - total + 1)
            if not line:
                break
            total += len(line)
            if total > MAX_MCP_RESPONSE_BYTES:
                raise PreflightError(f"MCP {method} event stream exceeded the bounded size limit")
            if line in (b"\n", b"\r\n"):
                if data_lines:
                    raw = b"".join(data_lines)
                    data_lines.clear()
                    try:
                        candidate = json.loads(raw.decode("utf-8", errors="strict"))
                    except (json.JSONDecodeError, UnicodeDecodeError):
                        continue
                    if isinstance(candidate, dict) and candidate.get("id") == expected_id:
                        return candidate
                continue
            if line.startswith(b"data:"):
                data_lines.append(line[5:].lstrip())
                data_lines.append(b"\n")
        raise PreflightError(f"MCP {method} event stream ended without its result")

    def tool(self, name, **arguments):
        result = self.rpc("tools/call", {"name": name, "arguments": arguments})
        if (not isinstance(result, dict) or result.get("isError", False) is not False or
                "result" in result or "error" in result):
            raise PreflightError(f"Authenticated MCP status call failed: {name}")
        # These Burp handlers return JSON in TextContent, not structured output.
        # Never let an alternate payload conceal missing/denied text evidence.
        if "structuredContent" in result:
            raise PreflightError(f"MCP {name} returned an unexpected structured result")
        content = result.get("content")
        if (not isinstance(content, list) or not content or any(
                not isinstance(item, dict) or item.get("type") != "text" or
                not isinstance(item.get("text"), str) or not item["text"].strip()
                for item in content)):
            raise PreflightError(f"MCP {name} returned an unreadable result")
        text_blocks = [item["text"] for item in content]
        try:
            decoded = json.loads("\n".join(text_blocks))
        except json.JSONDecodeError as error:
            raise PreflightError(f"MCP {name} returned an unreadable result") from error
        if not isinstance(decoded, (dict, list)):
            raise PreflightError(f"MCP {name} returned an unexpected scalar result")
        return decoded


def read_mcp_snapshot(client):
    connection = client.tool("burp_check_connection", includeBurpVersion=True)
    server = client.tool("burp_get_status", includeDiagnostics=False)
    scope = client.tool("burp_get_scope", urls=list(LOCAL_TEST_URLS))
    interception = client.tool("burp_get_intercept_status", includeDiagnostics=False)
    requests = client.tool("burp_list_pending_requests", includeDiagnostics=False)
    responses = client.tool("burp_list_pending_responses", includeDiagnostics=False)
    return {
        "connection": connection,
        "server": server,
        "scope": scope,
        "interception": interception,
        "requests": requests,
        "responses": responses,
    }


def _all_local_targets_eligible(snapshot):
    scope = snapshot.get("scope")
    checks = scope.get("checks") if isinstance(scope, dict) else None
    if not isinstance(checks, list):
        return False, "localhost scope results are missing"
    by_url = {item.get("url"): item for item in checks if isinstance(item, dict)}
    if len(by_url) != len(LOCAL_TEST_URLS) or set(by_url) != set(LOCAL_TEST_URLS):
        return False, "scope results do not match the nine fixed localhost targets"
    if any(
        by_url[url].get("inBurpScope") is not True
        or by_url[url].get("hostAllowlisted") is not True
        or by_url[url].get("eligible") is not True
        for url in LOCAL_TEST_URLS
    ):
        return False, "one or more fixed localhost targets are not scope- and allowlist-eligible"
    return True, None


def _identity_values(mode):
    if not isinstance(mode, dict) or mode.get("active") is not True:
        raise PreflightError("Unattended local test mode is not active; no session was requested")
    run_id = mode.get("testRunId")
    server_identity = mode.get("serverIdentity")
    if not isinstance(run_id, str) or not re.fullmatch(
        r"[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}", run_id
    ):
        raise PreflightError("Active Burp run identity is missing or malformed")
    if not isinstance(server_identity, str) or not TOKEN_PATTERN.fullmatch(server_identity):
        raise PreflightError("Active Burp server identity is missing or malformed")
    return run_id, server_identity


def discover_active_identities(minimum_authorization_ms):
    """Return active identities to a parent process for in-memory environment handoff only."""
    client = initialize()
    snapshot = read_mcp_snapshot(client)
    mode = snapshot.get("interception", {}).get("unattendedMode")
    run_id, server_identity = _identity_values(mode)
    failures = validate_setup_snapshot(snapshot, run_id, server_identity)
    scope_ok, scope_failure = _all_local_targets_eligible(snapshot)
    if scope_failure:
        failures.append(scope_failure)
    if snapshot.get("server", {}).get("authorizedTargetCount") != 1:
        failures.append("MCP allowlist does not contain exactly the configured localhost target")
    remaining = mode.get("remainingMillis", 0)
    try:
        remaining = int(remaining)
    except (TypeError, ValueError):
        remaining = 0
    if remaining < minimum_authorization_ms:
        failures.append(
            f"Unattended authorization has less than {minimum_authorization_ms // 1000}s "
            "for fixture setup and a bounded live session"
        )
    if failures:
        raise PreflightError("; ".join(dict.fromkeys(failures)))
    return {
        "testRunId": run_id,
        "serverIdentity": server_identity,
        "scopeEligibleCount": len(LOCAL_TEST_URLS),
        "authorizationRemainingMillis": remaining,
        "identitiesReturnedOnStdout": True,
    }


def start_supervised_session(session_lifetime_seconds):
    """Request one policy-bounded session only when unattended policy can auto-authorize it."""
    if session_lifetime_seconds < 150 or session_lifetime_seconds > 600:
        raise PreflightError("Requested session lifetime must be between 150 and 600 seconds")
    client = initialize()
    expected_run_id, expected_server_identity = unattended_identity_from_environment()
    if expected_run_id is None:
        raise PreflightError("Active unattended identities are required; no session was requested")
    snapshot = read_mcp_snapshot(client)
    failures = validate_setup_snapshot(snapshot, expected_run_id, expected_server_identity)
    scope_ok, scope_failure = _all_local_targets_eligible(snapshot)
    if scope_failure:
        failures.append(scope_failure)
    if snapshot.get("server", {}).get("authorizedTargetCount") != 1:
        failures.append("MCP allowlist does not contain exactly the configured localhost target")
    mode = snapshot.get("interception", {}).get("unattendedMode", {})
    try:
        authorization_remaining = int(mode.get("remainingMillis", 0))
    except (TypeError, ValueError):
        authorization_remaining = 0
    # The requested duration must fit the authorization, with a small transport margin.
    required_authorization_ms = session_lifetime_seconds * 1000 + 10_000
    if authorization_remaining < required_authorization_ms:
        failures.append(
            f"Unattended authorization has less than {required_authorization_ms // 1000}s "
            "to authorize the requested interception lifetime"
        )
    if failures:
        raise PreflightError("; ".join(dict.fromkeys(failures)) + "; no session was requested")

    client.tool(
        "burp_set_live_interception_state",
        enabled=True,
        sessionLifetimeSeconds=session_lifetime_seconds,
    )
    interception = client.tool("burp_get_intercept_status", includeDiagnostics=False)
    verification_snapshot = dict(snapshot)
    verification_snapshot["interception"] = interception
    final_failures = validate_mcp_snapshot(
        verification_snapshot,
        unattended_run_id=expected_run_id,
        unattended_server_identity=expected_server_identity,
        minimum_session_lifetime_seconds=session_lifetime_seconds,
    )
    if final_failures:
        raise PreflightError("Session start did not pass final checks: " + "; ".join(final_failures))
    return {
        "enabled": True,
        "heartbeatHealth": interception.get("heartbeatHealth"),
        "sessionLifetimeSeconds": interception.get("sessionLifetimeSeconds"),
        "sessionRemainingMillis": interception.get("sessionRemainingMillis"),
        "authorizationRemainingMillis": interception.get("unattendedMode", {}).get("remainingMillis"),
        "pendingRequests": interception.get("pendingRequests"),
        "pendingResponses": interception.get("pendingResponses"),
    }


def _raw_tool(client, name, arguments):
    result = client.rpc("tools/call", {"name": name, "arguments": arguments})
    if not isinstance(result, dict):
        raise PreflightError(f"MCP {name} returned a malformed tool result")
    return result


def _expect_stale_id_rejected(client, name, arguments):
    result = _raw_tool(client, name, arguments)
    if result.get("isError") is not True:
        raise PreflightError(f"Dropped message ID was unexpectedly accepted by {name}")


def drop_matching_request(wait_seconds=35):
    """Drop exactly one held GET /test-cancel and verify policy, stale ID, and queue evidence."""
    client = initialize()
    expected_run_id, expected_server_identity = unattended_identity_from_environment()
    if expected_run_id is None:
        raise PreflightError("Active unattended identities are required; no held message was changed")
    deadline = time.monotonic() + max(1, min(wait_seconds, 45))
    ticket = None
    while time.monotonic() < deadline:
        pending = client.tool("burp_list_pending_requests", includeDiagnostics=False)
        if not isinstance(pending, list):
            raise PreflightError("Pending request listing is malformed; no message was dropped")
        if pending:
            if len(pending) != 1:
                raise PreflightError("Unexpected request queue contents; no message was dropped")
            candidate = pending[0]
            if (
                not isinstance(candidate, dict)
                or candidate.get("kind", "request") != "request"
                or candidate.get("method") != "GET"
                or candidate.get("hostname") != "127.0.0.1"
                or candidate.get("urlPath") != "/test-cancel"
                or not isinstance(candidate.get("id"), str)
                or not candidate.get("id")
                or not isinstance(candidate.get("revision"), int)
            ):
                raise PreflightError("The only held request is not the exact synthetic cancellation target")
            ticket = candidate
            break
        time.sleep(0.5)
    if ticket is None:
        raise PreflightError("No matching /test-cancel request arrived before the bounded queue wait ended")

    status = client.tool("burp_get_intercept_status", includeDiagnostics=False)
    mode = status.get("unattendedMode", {}) if isinstance(status, dict) else {}
    if (
        status.get("enabled") is not True
        or status.get("heartbeatHealth") != "HEALTHY"
        or status.get("sessionEndReason") != "NONE"
        or status.get("timeoutSeconds") != INTERCEPTED_MESSAGE_TIMEOUT_MS // 1000
        or status.get("pendingRequests") != 1
        or status.get("pendingResponses") != 0
        or mode.get("active") is not True
        or mode.get("testRunId") != expected_run_id
        or mode.get("serverIdentity") != expected_server_identity
        or int(status.get("sessionRemainingMillis", 0)) < MIN_REMAINING_MS
        or int(mode.get("remainingMillis", 0)) < MIN_REMAINING_MS
        or int(status.get("leaseRemainingMillis", 0)) <= 0
    ):
        raise PreflightError("Live session or unattended authorization is no longer eligible; held request was not changed")
    scope = client.tool("burp_get_scope", urls=[TARGET_URL])
    checks = scope.get("checks", []) if isinstance(scope, dict) else []
    if len(checks) != 1 or checks[0].get("url") != TARGET_URL or checks[0].get("eligible") is not True:
        raise PreflightError("/test-cancel lost exact scope eligibility; held request was not changed")

    result = _raw_tool(client, "burp_drop_intercepted_request", {"id": ticket["id"]})
    if result.get("isError") is True:
        raise PreflightError("Burp did not approve the exact held request drop")
    content_text = " ".join(
        item.get("text", "") for item in result.get("content", [])
        if isinstance(item, dict) and item.get("type") == "text"
    )
    if "DROPPED" not in content_text.upper():
        raise PreflightError("Burp did not report the requested held request as dropped")

    final_status = client.tool("burp_get_intercept_status", includeDiagnostics=False)
    requests = client.tool("burp_list_pending_requests", includeDiagnostics=False)
    responses = client.tool("burp_list_pending_responses", includeDiagnostics=False)
    diagnostics = client.tool("burp_get_intercept_diagnostics", count=100)
    events = diagnostics.get("events", []) if isinstance(diagnostics, dict) else []
    drop_marker = f"request {ticket['id']} revision={ticket['revision']}"
    policy_marker = f"message={ticket['id']} revision={ticket['revision']}"
    drop_event = any(
        isinstance(event, dict)
        and event.get("action") == "intercept_drop"
        and event.get("outcome") == "dropped"
        and drop_marker in str(event.get("detail", ""))
        for event in events
    )
    auto_event = any(
        isinstance(event, dict)
        and event.get("action") == "unattended_local_test"
        and event.get("outcome") == "auto_approved"
        and "operation=DROP_REQUEST" in str(event.get("detail", ""))
        and "path=/test-cancel" in str(event.get("detail", ""))
        and policy_marker in str(event.get("detail", ""))
        for event in events
    )
    if final_status.get("pendingRequests") != 0 or final_status.get("pendingResponses") != 0 or requests or responses:
        raise PreflightError("Dropped message did not leave both interception queues empty")
    if not drop_event:
        raise PreflightError("Burp diagnostics do not confirm DROPPED for the matching request revision")

    _expect_stale_id_rejected(client, "burp_get_intercepted_request", {"id": ticket["id"]})
    _expect_stale_id_rejected(client, "burp_propose_intercepted_request_edit", {
        "id": ticket["id"], "revision": ticket["revision"], "headers": {}, "removeHeaders": [],
    })
    _expect_stale_id_rejected(client, "burp_forward_intercepted_request", {
        "id": ticket["id"], "revision": ticket["revision"],
    })
    return {
        "dropState": "DROPPED",
        "approvalMode": "AUTOMATIC" if auto_event else "UNATTRIBUTED",
        "automaticApprovalEvidence": auto_event,
        "staleGetRejected": True,
        "staleEditRejected": True,
        "staleForwardRejected": True,
        "pendingRequests": 0,
        "pendingResponses": 0,
    }


def stop_session_if_safe():
    """Stop only this mode-bound session after both queues are empty; never invoke the emergency dialog."""
    client = initialize()
    status = client.tool("burp_get_intercept_status", includeDiagnostics=False)
    if status.get("enabled") is not True:
        return {"stopped": True, "alreadyInactive": True}
    mode = status.get("unattendedMode", {})
    expected_run_id, expected_server_identity = unattended_identity_from_environment()
    if (
        expected_run_id is None
        or mode.get("active") is not True
        or mode.get("testRunId") != expected_run_id
        or mode.get("serverIdentity") != expected_server_identity
    ):
        raise PreflightError("Active session is not bound to the supplied live unattended identities; it was left unchanged")
    requests = client.tool("burp_list_pending_requests", includeDiagnostics=False)
    responses = client.tool("burp_list_pending_responses", includeDiagnostics=False)
    if requests or responses or status.get("pendingRequests") != 0 or status.get("pendingResponses") != 0:
        raise PreflightError("Queues are not empty; active interception was left unchanged")
    client.tool("burp_set_live_interception_state", enabled=False)
    final_status = client.tool("burp_get_intercept_status", includeDiagnostics=False)
    if final_status.get("enabled") is not False:
        raise PreflightError("Interception stop did not complete")
    return {"stopped": True, "alreadyInactive": False, "pendingRequests": 0, "pendingResponses": 0}


def check_proxy_listener():
    try:
        connection = socket.create_connection((PROXY_HOST, PROXY_PORT), timeout=2)
        connection.close()
    except OSError as error:
        raise PreflightError("Burp Proxy is not accepting loopback connections") from error


def check_test_server_health(expected_run_id=None, expected_server_identity=None,
                             connection_factory=http.client.HTTPConnection):
    if bool(expected_run_id) != bool(expected_server_identity):
        raise PreflightError("Both unattended local test identity values are required for the health check")
    connection = connection_factory("127.0.0.1", 8000, timeout=3)
    try:
        headers = {"Connection": "close"}
        if expected_run_id is not None:
            headers["X-MCP-Test-Run"] = expected_run_id
            headers["X-MCP-Server-Identity"] = expected_server_identity
        connection.request("GET", HEALTH_PATH, headers=headers)
        response = connection.getresponse()
        body = response.read(128)
        if response.status != 200 or body != HEALTH_BODY:
            raise PreflightError("Local test server health check did not match the expected response")
        if expected_run_id is not None and response.getheader("X-MCP-Test-Run") != expected_run_id:
            raise PreflightError("Local test server run identity did not match the active Burp authorization")
        if expected_server_identity is not None and response.getheader("X-MCP-Server-Identity") != expected_server_identity:
            raise PreflightError("Local test server identity did not match the active Burp authorization")
    except PreflightError:
        raise
    except Exception as error:
        raise PreflightError(f"Local test server is not responding ({type(error).__name__})") from error
    finally:
        connection.close()


def initialize(client=None):
    client = client or McpClient()
    initialized = client.rpc(
        "initialize",
        {
            "protocolVersion": PROTOCOL_VERSION,
            "capabilities": {},
            "clientInfo": {"name": "phase4a-cancel-preflight", "version": "1"},
        },
    )
    if not isinstance(initialized, dict) or not initialized.get("protocolVersion"):
        raise PreflightError("MCP initialization returned an invalid protocol result")
    client._protocol_version = initialized["protocolVersion"]
    client.rpc("notifications/initialized", notification=True)
    return client


def verify_authentication(client=None):
    """Authenticate using supported MCP initialization and a read-only status tool."""
    client = initialize(client or McpClient())
    status = client.tool("burp_get_status", includeDiagnostics=False)
    if not isinstance(status, dict) or status.get("serverState") != "running":
        raise PreflightError("Authenticated MCP status is unavailable or not running")
    if status.get("bearerAuthenticationRequired") is not True:
        raise PreflightError("MCP bearer authentication is not confirmed")
    return client


def unattended_identity_from_environment():
    expected_run_id = os.environ.get("BURP_TEST_RUN_ID")
    expected_server_identity = os.environ.get("BURP_TEST_SERVER_IDENTITY")
    if bool(expected_run_id) != bool(expected_server_identity):
        raise PreflightError("BURP_TEST_RUN_ID and BURP_TEST_SERVER_IDENTITY must be supplied together")
    if expected_run_id is not None and not re.fullmatch(r"[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}", expected_run_id):
        raise PreflightError("BURP_TEST_RUN_ID is malformed")
    if expected_server_identity is not None and not TOKEN_PATTERN.fullmatch(expected_server_identity):
        raise PreflightError("BURP_TEST_SERVER_IDENTITY is malformed")
    return expected_run_id, expected_server_identity


def run_setup_preflight():
    """Check auth, identity, scope, proxy and fixture before live interception starts."""
    client = initialize()
    expected_run_id, expected_server_identity = unattended_identity_from_environment()
    if expected_run_id is None:
        raise PreflightError("Active unattended test identities are required for setup; request was not sent")

    check_proxy_listener()
    check_test_server_health(expected_run_id, expected_server_identity)

    final_snapshot = read_mcp_snapshot(client)
    failures = validate_setup_snapshot(
        final_snapshot,
        unattended_run_id=expected_run_id,
        unattended_server_identity=expected_server_identity,
    )
    if failures:
        raise PreflightError("; ".join(failures))
    authorization_seconds = int(
        final_snapshot["interception"]["unattendedMode"]["remainingMillis"]
    ) // 1000
    print(
        "SETUP PREFLIGHT PASS: authenticated MCP, expected Burp build/version, Proxy listener, "
        "test-server identity, scope/allowlist and empty queues verified; live interception is off; "
        f"unattended authorization {authorization_seconds}s remain. /test-cancel was not sent."
    )


def run_preflight(minimum_session_lifetime_seconds=300):
    client = initialize()
    expected_run_id, expected_server_identity = unattended_identity_from_environment()
    if expected_run_id is None:
        raise PreflightError("Active unattended test identities are required; request was not sent")

    check_proxy_listener()
    check_test_server_health(expected_run_id, expected_server_identity)

    final_snapshot = read_mcp_snapshot(client)
    failures = validate_mcp_snapshot(
        final_snapshot,
        unattended_run_id=expected_run_id,
        unattended_server_identity=expected_server_identity,
        minimum_session_lifetime_seconds=minimum_session_lifetime_seconds,
    )
    if failures:
        raise PreflightError("; ".join(failures))

    remaining_seconds = int(final_snapshot["interception"]["sessionRemainingMillis"]) // 1000
    authorization_seconds = int(
        final_snapshot["interception"]["unattendedMode"]["remainingMillis"]
    ) // 1000
    print(
        "PREFLIGHT PASS: authenticated MCP, expected Burp build/version, Proxy listener, "
        "test-server health, scope/allowlist, active healthy session, empty queues; "
        f"session {remaining_seconds}s and unattended authorization {authorization_seconds}s remain. "
        "/test-cancel was not sent."
    )


def main(argv=None):
    args = list(sys.argv[1:] if argv is None else argv)
    try:
        if args == ["--auth-only"]:
            verify_authentication()
            print("AUTH PASS: authenticated MCP initialization and read-only status succeeded; token was not displayed.")
        elif args == ["--setup-only"]:
            run_setup_preflight()
        elif not args:
            run_preflight()
        elif len(args) == 2 and args[0] == "--minimum-session-seconds":
            try:
                seconds = int(args[1])
            except ValueError as error:
                raise PreflightError("Minimum session duration must be an integer") from error
            if seconds < 150 or seconds > 600:
                raise PreflightError("Minimum session duration must be between 150 and 600 seconds")
            run_preflight(minimum_session_lifetime_seconds=seconds)
        elif len(args) == 2 and args[0] == "--coordinator-identities":
            try:
                requested_seconds = int(args[1])
            except ValueError as error:
                raise PreflightError("Requested session duration must be an integer") from error
            if requested_seconds < 150 or requested_seconds > 600:
                raise PreflightError("Requested session duration must be between 150 and 600 seconds")
            identities = discover_active_identities(requested_seconds * 1000 + 15_000)
            print(json.dumps(identities, separators=(",", ":")))
        elif len(args) == 2 and args[0] == "--start-session":
            try:
                seconds = int(args[1])
            except ValueError as error:
                raise PreflightError("Requested session duration must be an integer") from error
            print(json.dumps(start_supervised_session(seconds), separators=(",", ":")))
        elif len(args) == 2 and args[0] == "--drop-matching-request":
            try:
                wait_seconds = int(args[1])
            except ValueError as error:
                raise PreflightError("Queue wait duration must be an integer") from error
            print(json.dumps(drop_matching_request(wait_seconds), separators=(",", ":")))
        elif args == ["--stop-session-if-safe"]:
            print(json.dumps(stop_session_if_safe(), separators=(",", ":")))
        else:
            raise PreflightError("Unsupported preflight option; request was not sent")
    except PreflightError as error:
        print(f"PREFLIGHT FAIL: {error}; request was not sent.", file=sys.stderr)
        return 2
    except Exception as error:
        print(
            f"PREFLIGHT FAIL: internal preflight error ({type(error).__name__}); request was not sent.",
            file=sys.stderr,
        )
        return 3
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
